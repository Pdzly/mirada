#!/usr/bin/env bash
set -euo pipefail

python_version=3.12.13

if [[ $# -ne 1 ]]; then
    echo "Usage: ${0##*/} TARGET_DIRECTORY" >&2
    exit 2
fi

repo_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
mkdir -p -- "$1"
target=$(cd -- "$1" && pwd)
for path in python licenses THIRD-PARTY-NOTICES.txt; do
    if [[ -e "$target/$path" || -L "$target/$path" ]]; then
        echo "Runtime destination already exists: $target/$path" >&2
        exit 1
    fi
done

stage=$(mktemp -d "$target/.runtime.XXXXXX")
trap 'rm -rf -- "$stage"' EXIT

export UV_PYTHON_PREFERENCE=only-managed
uv python install --no-bin "$python_version"
python_executable=$(uv python find --no-project "$python_version")
python_path=$(realpath -- "$python_executable")
cp -a -- "$(dirname -- "$python_path")/.." "$stage/python"
uv build --wheel --out-dir "$stage/wheels" "$repo_root"
uv pip install --python "$stage/python/bin/python3" --break-system-packages \
    --link-mode copy --only-binary :all: "$stage/wheels/"*.whl

stdlib=$("$stage/python/bin/python3" -ISB -c 'import sysconfig; print(sysconfig.get_path("stdlib"))')
site_packages=$("$stage/python/bin/python3" -ISB -c 'import sysconfig; print(sysconfig.get_path("purelib"))')
rm -rf -- "$stdlib/ensurepip" "$site_packages/pip" "$site_packages"/pip-*.dist-info
# Entry points generated by wheel installation refer to the staging directory.
rm -f -- "$stage/python/bin"/pip*
for executable in "$stage/python/bin/"*; do
    if [[ -f "$executable" ]] && grep -IFq -- "$stage" "$executable"; then
        rm -f -- "$executable"
    fi
done
rm -f -- "$site_packages"/mirada-*.dist-info/direct_url.json
find "$stage/python" -type d -name __pycache__ -prune -exec rm -rf -- {} +

"$stage/python/bin/python3" -IB - "$stage" "$repo_root" "$stdlib" <<'PY'
import os
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from importlib import metadata
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit
from urllib.request import urlopen

stage, repo, stdlib = map(Path, sys.argv[1:])


def git_read(*args):
    if not (repo / ".git").exists() or not shutil.which("git"):
        return ""
    result = subprocess.run(
        ["git", "-C", str(repo), *args],
        env={**os.environ, "GIT_OPTIONAL_LOCKS": "0"},
        capture_output=True,
        text=True,
    )
    return result.stdout.strip() if result.returncode == 0 else ""


def public_repository_url(remote):
    if "://" not in remote and "@" in remote and ":" in remote:
        host, path = remote.split("@", 1)[1].split(":", 1)
        remote = f"ssh://{host}/{path}"
    try:
        url = urlsplit(remote)
        if url.scheme not in ("https", "http", "ssh", "git") or not url.hostname:
            return ""
        host = url.hostname
        if ":" in host:
            host = f"[{host}]"
        if url.scheme in ("http", "https") and url.port:
            host = f"{host}:{url.port}"
        path = url.path.rstrip("/").removesuffix(".git")
        return urlunsplit(("https", host, path, "", "")) if path else ""
    except ValueError:
        return ""


repository_url = (
    public_repository_url(os.environ.get("MIRADA_SOURCE_URL", ""))
    or public_repository_url(git_read("remote", "get-url", "origin"))
    or "https://github.com/jleiva831/mirada"
)
commit = git_read("rev-parse", "HEAD")
dirty = " (dirty working tree)" if commit and git_read("status", "--porcelain") else ""

licenses = stage / "licenses"
python_licenses = licenses / "CPython"
python_licenses.mkdir(parents=True)
shutil.copyfile(stdlib / "LICENSE.txt", python_licenses / "LICENSE.txt")
python_version = ".".join(map(str, sys.version_info[:3]))
python_build = (stage / "python" / "BUILD").read_text().strip()
notices = [
    "Mirada third-party notices",
    "",
    "The source code corresponding to the distributed versions is available at",
    "the links below. License and copyright texts are under licenses/.",
    "",
    f"CPython {python_version} (Python-2.0; see license text for bundled components)",
    f"  CPython source: https://www.python.org/ftp/python/{python_version}/Python-{python_version}.tar.xz",
    "  Python build recipes and release:",
    f"  https://github.com/astral-sh/python-build-standalone/releases/tag/{python_build}",
    "",
    "Installed wheels",
]

qt_version = metadata.version("PySide6-Essentials")
for dist in sorted(metadata.distributions(), key=lambda item: item.metadata["Name"].lower()):
    name = dist.metadata["Name"]
    version = dist.version
    license_id = dist.metadata.get("License-Expression") or dist.metadata.get("License")
    if not license_id or "\n" in license_id:
        license_id = "See included license texts"
    notices.append(f"- {name}=={version} ({license_id})")
    if name.lower() == "mirada":
        notices.append(f"  Repository: {repository_url}")
        if commit:
            notices.append(f"  Build commit: {commit}{dirty}")
            if urlsplit(repository_url).hostname == "github.com":
                notices.append(f"  Source at build commit: {repository_url}/tree/{commit}")
        else:
            notices.append("  Build commit: unavailable in this source checkout")
    else:
        notices.append(f"  Release and source links: https://pypi.org/project/{name}/{version}/")
    for entry in dist.files or ():
        parts = entry.parts
        if len(parts) < 2 or not parts[0].endswith(".dist-info"):
            continue
        if parts[1].lower() == "licenses" or parts[1].upper().startswith(("LICENSE", "COPYING", "NOTICE")):
            source = dist.locate_file(entry)
            if source.is_file():
                destination = licenses / name / Path(*parts[1:])
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, destination)

qt_series = qt_version.rsplit(".", 1)[0]
notices.extend([
    "",
    f"Qt {qt_version} (LGPL-3.0-only and other licenses; see upstream notices)",
    f"  Qt source: https://download.qt.io/archive/qt/{qt_series}/{qt_version}/single/qt-everywhere-src-{qt_version}.tar.xz",
    f"  PySide6 and Shiboken source: https://github.com/pyside/pyside-setup/tree/v{qt_version}",
])

# These wheels may omit the Qt and Qt for Python license texts.
def download_license(entry):
    project, upstream, filename = entry
    destination = licenses / project / filename
    destination.parent.mkdir(parents=True, exist_ok=True)
    url = f"https://raw.githubusercontent.com/{upstream}/v{qt_version}/LICENSES/{filename}"
    with urlopen(url, timeout=30) as response:
        destination.write_bytes(response.read())


qt_files = ("LGPL-3.0-only.txt", "GPL-2.0-only.txt", "GPL-3.0-only.txt", "Qt-GPL-exception-1.0.txt")
with ThreadPoolExecutor(max_workers=4) as pool:
    list(pool.map(download_license, [
        (project, upstream, filename)
        for project, upstream in (("Qt", "qt/qtbase"), ("Qt-for-Python", "pyside/pyside-setup"))
        for filename in qt_files
    ]))

(stage / "THIRD-PARTY-NOTICES.txt").write_text("\n".join(notices) + "\n", encoding="utf-8")
PY
if grep -rIlF -- "$stage" "$stage/python"; then
    echo "Runtime still contains staging paths." >&2
    exit 1
fi
mv -T -- "$stage/python" "$target/python"
mv -T -- "$stage/licenses" "$target/licenses"
mv -T -- "$stage/THIRD-PARTY-NOTICES.txt" "$target/THIRD-PARTY-NOTICES.txt"
